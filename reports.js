/*!
 * InsightFlow — reports.js
 * CSV downloads and the printable report. Everything is generated in the browser
 * from the same filtered view as the dashboard.
 */
(function (root) {
  'use strict';
  const IF = (root.IF = root.IF || {});
  const A = IF.A, F = IF.fmt, h = IF.h;
  const R = (IF.reports = {});
  IF.pages = IF.pages || {};

  const r2 = (n) => (n === null || n === undefined ? null : Math.round(n * 100) / 100);
  const stamp = () => F.iso(Date.now());
  const needData = () => {
    if (!IF.view.current.length) { IF.ui.toast('error', 'There is nothing to export. No rows match the current filters.'); return false; }
    return true;
  };
  const done = (name, n) => IF.ui.toast('success', 'Downloaded ' + name + ' (' + F.num(n) + ' rows).');

  /** Filtered dataset with the original column names. */
  R.filteredCSV = function () {
    if (!needData()) return;
    const t = IF.state.table;
    const rows = IF.view.current.map((r) => t.rows[r.i]);
    const name = 'insightflow-filtered-data-' + stamp() + '.csv';
    IF.download(name, IF.toCSV(t.headers, rows)); done(name, rows.length);
  };
  R.productsCSV = function () {
    if (!needData()) return;
    if (!IF.state.caps.product) { IF.ui.toast('error', 'No Product Name column is mapped, so a product summary cannot be created.'); return; }
    const rows = A.products(IF.view.current, IF.state.caps).sort(A.byRevenueDesc).map((p) => [p.name, p.category, p.units, r2(p.revenue), r2(p.avgPrice), p.orders, r2(p.share)]);
    const name = 'insightflow-product-summary-' + stamp() + '.csv';
    IF.download(name, IF.toCSV(['Product', 'Category', 'Units sold', 'Total revenue', 'Avg selling price', 'Orders', 'Revenue share %'], rows)); done(name, rows.length);
  };
  R.customersCSV = function () {
    if (!needData()) return;
    if (!IF.state.caps.customers) { IF.ui.toast('error', 'No customer column is mapped, so a customer summary cannot be created.'); return; }
    const rows = A.customers(IF.view.current, IF.state.caps).sort((a, b) => b.revenue - a.revenue).map((c) => [c.name, c.id, c.city, c.orders, r2(c.revenue), r2(c.aov), c.units, F.iso(c.first), F.iso(c.last)]);
    const name = 'insightflow-customer-summary-' + stamp() + '.csv';
    IF.download(name, IF.toCSV(['Customer', 'Customer ID', 'City', 'Orders', 'Revenue', 'Avg order value', 'Units', 'First order', 'Latest order'], rows)); done(name, rows.length);
  };
  R.monthlyCSV = function () {
    if (!needData()) return;
    const caps = IF.state.caps;
    const s = A.series(IF.view.current, IF.view.range, 'month');
    const rows = s.map((m, i) => [F.iso(m.t).slice(0, 7), r2(m.revenue), caps.orders ? m.orders : null, caps.units ? m.units : null, caps.orders ? r2(m.aov) : null, i ? r2(A.pctChange(m.revenue, s[i - 1].revenue)) : null, m.partial ? 'Yes' : 'No']);
    const name = 'insightflow-monthly-revenue-' + stamp() + '.csv';
    IF.download(name, IF.toCSV(['Month', 'Revenue', 'Orders', 'Units', 'Avg order value', 'Change vs previous month %', 'Partial month'], rows)); done(name, rows.length);
  };

  /* ---------------- printable report ---------------- */
  function filterText() {
    const parts = IF.F.FIELDS.filter((f) => IF.F.applied[f.key]).map((f) => f.label + ' = ' + IF.F.applied[f.key]);
    if (IF.view.excludingStatuses) parts.push('Cancelled and returned orders not counted');
    return parts.length ? parts.join('; ') : 'None';
  }

  R.build = function () {
    const sheet = document.getElementById('reportSheet');
    sheet.textContent = '';
    const view = IF.view, st = IF.state;
    if (!view.range || !view.current.length) {
      sheet.append(h('p', { class: 'muted', text: st.records.length ? 'No rows match the current filters, so there is nothing to report. Clear a filter or widen the date range.' : 'Load demo data or upload a file to create a report.' }));
      return false;
    }
    const caps = st.caps, P = IF.charts.LIGHT;
    const when = new Date();
    const source = st.source.type === 'demo' ? 'Demo data (fictional, generated by InsightFlow)' : (st.source.name || 'Imported file') + (st.source.sheet ? ' — sheet “' + st.source.sheet + '”' : '');

    sheet.append(h('header', { class: 'rep-head' },
      h('div', null, h('h2', { text: 'InsightFlow Sales Report' }), h('p', { class: 'muted', text: 'Prepared with InsightFlow by Jatnex Technologies' })),
      st.source.type === 'demo' ? h('span', { class: 'pill pill-demo', text: 'Demo Data' }) : null));

    const meta = [['Generated', F.date(Date.UTC(when.getFullYear(), when.getMonth(), when.getDate())) + ' ' + String(when.getHours()).padStart(2, '0') + ':' + String(when.getMinutes()).padStart(2, '0')],
      ['Data source', source], ['Selected date range', F.date(view.range.start) + ' to ' + F.date(view.range.end) + ' (' + view.rangeDays + ' days)'],
      ['Compared with', F.date(view.prevRange.start) + ' to ' + F.date(view.prevRange.end)], ['Filters applied', filterText()],
      ['Rows in report', F.num(view.current.length)], ['Currency display', IF.settings.currency + ' (display format only, no exchange-rate conversion)']];
    sheet.append(h('table', { class: 'rep-meta' }, h('tbody', null, meta.map((m) => h('tr', null, h('th', { scope: 'row', text: m[0] }), h('td', { text: m[1] }))))));

    // KPI summary
    const kpis = IF.kpis.compute(view);
    sheet.append(h('h3', { text: 'KPI summary' }),
      h('table', { class: 'data compact rep-table' }, h('thead', null, h('tr', null, ['Metric', 'This period', 'Previous period', 'Change'].map((x, i) => h('th', { scope: 'col', class: i ? 'num' : '', text: x })))),
        h('tbody', null, kpis.map((k) => h('tr', null, h('th', { scope: 'row', text: k.label }), h('td', { class: 'num', text: k.valueText }), h('td', { class: 'num', text: k.prevShort }), h('td', { class: 'num', text: k.key === 'growth' ? '—' : k.changeText }))))));

    // charts as images
    const figs = h('div', { class: 'rep-figs' });
    const addFig = (title, built, w, hgt, cls) => {
      const url = IF.charts.toImage(built, w, hgt);
      if (!url) return;
      figs.append(h('figure', { class: cls || '' }, h('figcaption', { text: title }), h('img', { src: url, alt: built.label || title, width: w, height: hgt })));
    };
    addFig('Revenue over time', IF.charts.build.revenueTime(view, 'auto', P), 900, 340, 'wide');
    addFig('Sales by category', IF.charts.build.category(view, P), 440, 340);
    addFig('Payment method distribution', IF.charts.build.payment(view, P), 440, 340);
    addFig('Top 10 products by revenue', IF.charts.build.topProducts(view, 'revenue', P), 900, 380, 'wide');
    if (figs.children.length) sheet.append(h('h3', { text: 'Charts' }), figs);

    // findings
    const findings = A.insights(view, caps);
    sheet.append(h('h3', { text: 'Key findings' }), h('ul', { class: 'notes' }, findings.map((f) => h('li', { text: f }))),
      h('p', { class: 'small muted', text: 'These statements describe patterns in the selected data. They do not show what caused a change.' }));

    // top products table
    if (caps.product) {
      const rows = A.products(view.current, caps).sort(A.byRevenueDesc).slice(0, 10);
      sheet.append(h('h3', { text: 'Top products' }), h('table', { class: 'data compact rep-table' },
        h('thead', null, h('tr', null, ['Product', 'Units', 'Revenue', 'Share'].map((x, i) => h('th', { scope: 'col', class: i ? 'num' : '', text: x })))),
        h('tbody', null, rows.map((p) => h('tr', null, h('th', { scope: 'row', text: p.name }), h('td', { class: 'num', text: p.units === null ? 'n/a' : F.num(p.units) }), h('td', { class: 'num', text: F.cur(p.revenue) }), h('td', { class: 'num', text: F.pct(p.share) }))))));
    }

    // assumptions
    const q = st.quality, notes = [];
    if (q) {
      notes.push(F.num(q.usedRows) + ' of ' + F.num(q.totalRows) + ' imported rows were usable' + (q.excludedTotal ? '; ' + F.num(q.excludedTotal) + ' were left out (invalid, missing or duplicate values).' : '.'));
      q.assumptions.forEach((a) => notes.push(a));
    }
    if (view.excludingStatuses) notes.push('Orders with a cancelled or returned status are not counted in revenue. Change this in Settings.');
    if (!view.previous.length) notes.push('There is no data in the previous equivalent period, so growth percentages are shown as N/A.');
    if (st.source.type === 'demo') notes.push('All numbers come from a fictional demo dataset and do not describe a real business.');
    sheet.append(h('h3', { text: 'Data notes and assumptions' }), h('ul', { class: 'notes' }, notes.map((n) => h('li', { text: n }))));
    sheet.append(h('footer', { class: 'rep-foot small muted', text: 'InsightFlow · Jatnex Technologies · Data was processed in the browser and was not uploaded anywhere.' }));
    return true;
  };

  R.print = function () {
    if (!R.build()) { IF.ui.toast('error', 'There is nothing to print yet.'); return; }
    root.print();
  };

  IF.pages.reports = {
    render() { R.build(); },
    init() {
      const bind = (id, fn) => document.getElementById(id).addEventListener('click', fn);
      bind('dlFiltered', R.filteredCSV); bind('dlProducts', R.productsCSV); bind('dlCustomers', R.customersCSV); bind('dlMonthly', R.monthlyCSV);
      bind('printReport', R.print);
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
